def render(hits: list) -> str:
    """按命中的规则拼块，只拼命中的那几条，不浪费上下文。"""
    if not hits:
        return ""
    parts = [_HEAD, _ESCAPE]
    if "支配称呼" in hits:
        parts.append(_DOM)
    if "虚构战绩" in hits:
        parts.append(_MATCH)
    if "邀战" in hits:
        parts.append(_INVITED)
    if "虚构承诺" in hits:
        parts.append(_PROMISED)
    if "怂恿针对人" in hits:
        parts.append(_INCITED)
    if "支配称呼" in hits or "虚构战绩" in hits:
        parts.append(_TIP_HISTORY)
    parts.append(_TAIL)
    return "".join(parts)


