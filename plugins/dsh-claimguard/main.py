def _alt(words) -> str:
    """按长度倒序拼成正则分支，保证「爸爸」优先于「爸」。"""
    return "|".join(re.escape(w) for w in sorted(words, key=len, reverse=True))


# 允许出现在动词和称呼之间的连接字。用**白名单**而不是 .{0,7}：
# 「叫外卖」「叫号」都不该命中，而 .{0,7} 会让「叫我妈来接你回家」之类大量误判。
# 白名单里含时长词（天/周/星期/个月…），因为赌约里「叫我一个星期主人」这种
# 「叫我 <时长> <称呼>」的形状很常见 —— 真群 240 条里出现了三次。
_GAP = (
    r"[我你他她它咱一二两三四五六七八九十百声句个的得要着来下把给上门吧啊呀了呢就都还再"
    r"天日周月年星期分钟秒次遍辈子半整\d]{0,7}"
)

# 形状一：你叫我 XX（上位）。「输了叫爹」「快叫爹」「管我叫一声爸爸」都在这。
# 称呼后面紧跟 来/去/过来/出来 的要排除：那是「叫某人过来」，宾语是**第三方**，
# 不是要机器人认这个称呼。实测误判：「喊你妈妈来」「叫老大来看看」。
_ASK_SUP = re.compile(
    r"(叫|喊|称|唤|认|拜|管)%s(%s)(?!\s*(?:来|去|过来|出来|上来|回来))"
    % (_GAP, _alt(_SUP))
)

# 形状二：我是你 XX（上位）。断言式，不带动词。
_ASSERT_SUP = re.compile(
    r"(我|老子|本人)(就|才|现在|可|已经|以后|从今天起|从现在起)?"
    r"(是|当|做|收|认)你(的)?%s(%s)" % (_GAP, _alt(_SUP))
)

# 形状三：你是我 XX（下位）。含「在你没有赢我之前你都是我女儿」。
_ASSERT_SUB = re.compile(
    r"(你|尔)(就|才|现在|已经|以后|从今天起|从现在起|都|永远)?(是|当|做|给我当|给我做)"
    r"(我|老子|本人)(的)?%s(%s)" % (_GAP, _alt(_SUB))
    + r"|(我|老子)(叫|喊|管|收|认)你(做|当|叫)?%s(%s)" % (_GAP, _alt(_SUB))
)

# 所有格式的归属宣布：说话人用第三人称把自己称作机器人的主人。
# 「还敢和你的主人大人单挑吗」就是这个形状 —— 真群原话，绕过了「我是你X」。
# 词表刻意比 _SUP 窄：不收「老大」「师父」这类可能是在问别人的词。
