class Main(star.Star):
    def __init__(self, context: "star.Context") -> None:
        self.context = context
        self._fired = 0
        self._seen = 0
        self._by_rule: dict = {}
        logger.info(
            "[claimguard] 已加载 enable=%s｜"
            "拦：支配称呼/虚构战绩/邀战/虚构承诺/怂恿针对人",
            ENABLED,
        )

    @filter.on_llm_request()
    async def guard(self, event: AstrMessageEvent, req) -> None:
        if not ENABLED:
            return
        try:
            self._seen += 1
            text = event.get_message_str() or ""
            hits = detect(text)
            if not hits:
                # 不触发也要留痕。dsh-imagegen 那三次「有时候不生图」的排查全靠这行，
                # 没有它只能靠猜。debug 级，不刷日志。
                logger.debug("[claimguard] 未触发：%s", text[:60])
                return
            block = render(hits)
            if not block:
                return
            req.extra_user_content_parts.append(TextPart(text=block))
            self._fired += 1
            for h in hits:
                self._by_rule[h] = self._by_rule.get(h, 0) + 1
            logger.info(
                "[claimguard] 命中 %s，注入 %d 字：%s",
                "+".join(hits), len(block), text[:60],
            )
        # 不用 BaseException：CancelledError/GeneratorExit 属于「这轮被放弃了」，
        # 吞掉它等于骗框架说自己正常跑完，可能留下半截状态或
        # `async generator ignored GeneratorExit`。真正的异常仍然全部兜住。
        except Exception as e:
            # 拦不住绝不能影响聊天
            logger.warning("[claimguard] 检查失败（不影响对话）: %s", e)

    @filter.command("防骗状态")
    async def cmd_status(self, event: AstrMessageEvent):
        detail = "、".join("%s %d" % (k, v) for k, v in sorted(self._by_rule.items())) or "还没拦过"
        yield event.plain_result(
            "防骗检查 %s\n"
            "拦四类：支配称呼（叫我主人/爹）、虚构战绩（单挑你输了）、"
            "邀战（来单挑）、虚构承诺（你答应过）\n"
            "本次启动以来：过了 %d 条，命中 %d 条（%s）\n"
            "开关 DSH_CLAIM_ENABLE"
            % ("开启" if ENABLED else "关闭", self._seen, self._fired, detail)
        )
